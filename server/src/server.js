import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import authRouter from './routes/auth.js';
import eventsRouter from './routes/events.js';
import joinedRouter from './routes/joined.js';
const app=express();
app.use(cors({origin:(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(','),credentials:true}));
app.use(express.json({limit:'1mb'}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'TogetherWe API'}));
app.use('/api/auth',authRouter);app.use('/api/events',eventsRouter);app.use('/api/joined',joinedRouter);
app.use((req,res)=>res.status(404).json({message:'API route not found'}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'Something went wrong on the server'});});
export default app;
